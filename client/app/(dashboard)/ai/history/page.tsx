import Link from 'next/link';
import {redirect} from 'next/navigation';
import {getServerCookieHeader} from '@/lib/auth/server-auth';
import {ArrowLeft, ChevronLeft, ChevronRight, History} from 'lucide-react';

import {PageContainer} from '@/components/layout';
import GlassPanel from '@/components/shared/GlassPanel';
import {Button} from '@/components/ui/button';
import AiService from '@/services/ai.service';

import RecommendationHistoryList from './_components/RecommendationHistoryList';

type AIHistoryPageProps = {
    searchParams?: Promise<{
        page?: string;
    }>;
};

const HISTORY_PAGE_SIZE = 10;

export default async function AIHistoryPage({
    searchParams,
}: AIHistoryPageProps) {
    const resolvedSearchParams = await searchParams;

    const requestedPage = Number(resolvedSearchParams?.page);

    const currentPage =
        Number.isInteger(requestedPage) && requestedPage > 0
            ? requestedPage
            : 1;

    const cookieHeader = await getServerCookieHeader();

    const response = await AiService.getRecommendations(
        {
            type: 'car-recommendation',
            page: currentPage,
            limit: HISTORY_PAGE_SIZE,
        },
        {
            headers: {
                Cookie: cookieHeader,
            },
        },
    );

    const {recommendations, pagination} = response;

    if (pagination.totalPages > 0 && currentPage > pagination.totalPages) {
        redirect(`/ai/history?page=${pagination.totalPages}`);
    }

    const hasPreviousPage = pagination.page > 1;
    const hasNextPage = pagination.page < pagination.totalPages;

    return (
        <main className="page-shell">
            <PageContainer className="space-y-8 py-8 md:py-10">
                <Button
                    asChild
                    variant="ghost"
                    size="sm"
                    className="-ml-3 w-fit text-muted-foreground hover:text-foreground"
                >
                    <Link href="/ai">
                        <ArrowLeft className="size-4" aria-hidden="true" />
                        Back to AI advisor
                    </Link>
                </Button>

                <GlassPanel variant="elevated">
                    <div className="flex items-center gap-4">
                        <div className="flex size-12 items-center justify-center rounded-2xl bg-primary/10 text-primary">
                            <History className="size-6" aria-hidden="true" />
                        </div>

                        <div>
                            <p className="eyebrow">AI history</p>

                            <h1 className="page-title mt-2">
                                Previous recommendations
                            </h1>

                            <p className="body-text mt-2">
                                Browse car recommendations generated by the
                                global AI advisor.
                            </p>
                        </div>
                    </div>
                </GlassPanel>

                <RecommendationHistoryList recommendations={recommendations} />

                {pagination.totalPages > 1 ? (
                    <nav
                        aria-label="Recommendation history pagination"
                        className="flex items-center justify-between gap-4"
                    >
                        {hasPreviousPage ? (
                            <Button asChild variant="outline">
                                <Link
                                    href={`/ai/history?page=${pagination.page - 1}`}
                                >
                                    <ChevronLeft
                                        className="size-4"
                                        aria-hidden="true"
                                    />
                                    Previous
                                </Link>
                            </Button>
                        ) : (
                            <Button variant="outline" disabled>
                                <ChevronLeft
                                    className="size-4"
                                    aria-hidden="true"
                                />
                                Previous
                            </Button>
                        )}

                        <p className="text-sm text-muted-foreground">
                            Page {pagination.page} of {pagination.totalPages}
                        </p>

                        {hasNextPage ? (
                            <Button asChild variant="outline">
                                <Link
                                    href={`/ai/history?page=${pagination.page + 1}`}
                                >
                                    Next
                                    <ChevronRight
                                        className="size-4"
                                        aria-hidden="true"
                                    />
                                </Link>
                            </Button>
                        ) : (
                            <Button variant="outline" disabled>
                                Next
                                <ChevronRight
                                    className="size-4"
                                    aria-hidden="true"
                                />
                            </Button>
                        )}
                    </nav>
                ) : null}
            </PageContainer>
        </main>
    );
}
